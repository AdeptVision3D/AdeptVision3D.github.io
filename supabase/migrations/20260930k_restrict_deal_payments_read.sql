-- Сделки (deals) и переписка по ним (deal_activities) осознанно открыты всей
-- команде: цена/скидка/бесплатные пункты должен видеть художник на своём
-- проекте — это и есть механизм защиты от ситуации "менеджер пообещал
-- бесплатно, продакшн не в курсе" (см. комментарий в 20260930_crm_deals.sql).
-- Эту прозрачность не трогаем.
--
-- А вот deal_payments — это уже факт реально полученных денег от клиента
-- (бухгалтерия), а не согласованные условия. К работе над кадрами это
-- отношения не имеет, и художнику незачем видеть, сколько клиент уже
-- перевёл. Закрываем чтение до manager и выше, плюс marketer — у него уже
-- есть полный доступ к аналитике (включая вкладку "Финансы" в
-- analytics.html, которая как раз читает эту таблицу) — иначе вкладка
-- молча покажет пустые/нулевые цифры вместо реальных.
drop policy if exists deal_payments_select on public.deal_payments;
create policy deal_payments_select on public.deal_payments
  for select using (
    auth_role() = ANY (ARRAY['manager'::text, 'lead'::text, 'art_director'::text, 'ceo'::text, 'marketer'::text]) OR auth_is_admin()
  );
