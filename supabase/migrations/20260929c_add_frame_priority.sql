-- Ручной флаг "горящий кадр" — независим от статуса и дедлайна проекта,
-- просто позволяет отметить конкретный кадр как приоритетный (например,
-- клиент поторопил именно с этим ракурсом). Обновление статуса кадра
-- (frames.status) уже открыто всем через существующую политику UPDATE на
-- frames — по тому же пути идёт и это поле, отдельных прав не требуется.
alter table public.frames add column if not exists is_priority boolean not null default false;
